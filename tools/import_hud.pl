#!/usr/bin/env perl
# Rasterize the English in-game labels with Frozen Bubble's own SDLPango context.
use strict;
use warnings;
use FindBin;
use Encode qw(encode_utf8);
use SDL;
use SDL::Surface;
use SDL::PixelFormat;
use Games::FrozenBubble::CStuff;

SDL::init(0);
Games::FrozenBubble::CStuff::sdlpango_init();
my $ctx=Games::FrozenBubble::CStuff::sdlpango_createcontext('white','sans 14');
my $root="$FindBin::Bin/../FrozenBubble";
sub raster {
    my ($s,$shadow)=@_;
    my ($w,$h)=($s->w,$s->h);
    my $format=$s->format;
    die 'Expected 8-bit coverage' if ($format->Amask >> $format->Ashift)!=255;
    my $stride=$s->pitch/$format->BytesPerPixel;
    my @coverage;
    for my $y (0..$h-1) {
        push @coverage, [map { ($s->get_pixel($y*$stride+$_) >> $format->Ashift) & 255 } 0..$w-1];
    }
    # Desktop print_ blits a black shadow at (+1,+1), then its white face.
    my @rows;
    for my $y (0..$h) {
        my $row='';
        for my $x (0..$w) {
            my $fg=$y<$h && $x<$w ? $coverage[$y][$x] : 0;
            my $bg=$shadow && $y && $x ? $coverage[$y-1][$x-1] : 0;
            my $alpha=$fg+$bg*(1-$fg/255);
            my $gray=$alpha ? int(255*$fg/$alpha+0.5) : 255;
            $row.=pack('C4',$gray,$gray,$gray,int($alpha+0.5));
        }
        push @rows,$row;
    }
    return \@rows;
}
my @labels=('opening clock',0..9, 'Level ', 'Score: ', 'Random level', "'", '"');
my (@sprites,$max_width,$used_height);
$used_height=0; $max_width=0;
for my $label (@labels) {
    my $s=$label eq 'opening clock'
        ? Games::FrozenBubble::CStuff::sdlpango_draw_givenalignment($ctx,qq(2'00"),96,'center')
        : Games::FrozenBubble::CStuff::sdlpango_draw_givenalignment($ctx,"$label",-1,'left');
    my ($w,$h)=($s->w,$s->h);
    my $rows=raster($s,1);
    push @sprites,[$label,$w,$h,$used_height,$rows];
    $used_height+=$h+3;
    $max_width=$w+2 if $w+2>$max_width;
}
sub power_of_two { my $n=1; $n*=2 while $n<$_[0]; return $n }
my ($width,$height)=(power_of_two($max_width),power_of_two($used_height));
my $pixels="\0" x ($width*$height*4);
open my $meta,'>',"$root/HUDArt.lua" or die $!;
print $meta "-- Generated by tools/import_hud.pl using the desktop in-game font.\nlocal _,FB=...\n";
print $meta "FB.HUDArt={width=$width,height=$height,labels={\n";
for my $sprite (@sprites) {
    my ($label,$w,$h,$y,$rows)=@$sprite;
    for my $i (0..$#$rows) {
        substr($pixels,($y+$i)*$width*4,length($rows->[$i]),$rows->[$i]);
    }
    $label=~s/"/\\"/g;
    print $meta qq(    ["$label"]={y=$y,w=$w,h=$h},\n);
}
print $meta "}}\n";
print $meta 'FB.MediaInfo["opening-training-clock"]=FB.MediaInfo["training-clock"]', "\n";
close $meta or die $!;
open my $tga,'>:raw',"$root/Media/hud-lettering.tga" or die $!;
print $tga pack('CCCvvCvvvvCC',0,0,2,0,0,0,0,0,$width,$height,32,40),$pixels;
close $tga or die $!;

# Pack both network score fonts. Padding the text itself gives overhanging strokes
# (j, f, italic-looking accents) room outside the glyph's logical advance.
my @letters=(map(chr,32,39,45,46,48..58,65..90,97..122,192..255,0x100..0x17f,
                       0x400..0x45f,0x490,0x491,0x2019,0x2026),qw(ff fi fl ffi ffl));
my $sheet_width=512;
my ($x,$y,$line_height)=(0,0,0);
my @tiles;
open my $names,'>:encoding(UTF-8)',"$root/NameArt.lua" or die $!;
print $names "-- Generated by tools/import_hud.pl with the original SDLPango score fonts.\nlocal _,FB=...\nFB.NameArt={\n";
for my $size (14,8) {
    my $font=Games::FrozenBubble::CStuff::sdlpango_createcontext('white',"sans $size");
    my %advance;
    print $names "    [$size]={glyphs={\n";
    for my $letter (@letters) {
        my $utf8=encode_utf8($letter);
        my $w=Games::FrozenBubble::CStuff::sdlpango_getsize($font,$utf8,-1)->[0];
        $advance{$letter}=$w;
        my $start=Games::FrozenBubble::CStuff::sdlpango_getsize($font,' '.$utf8,-1)->[0]-$w;
        my $s=Games::FrozenBubble::CStuff::sdlpango_draw_givenalignment($font,' '.$utf8.' ',-1,'left');
        my $rows=raster($s,0);
        my ($l,$r,$t,$b)=($s->w,-1,$s->h,-1);
        for my $row (0..$#$rows) {
            for my $col (0..$s->w) {
                next unless ord(substr($rows->[$row],$col*4+3,1));
                $l=$col if $col<$l; $r=$col if $col>$r;
                $t=$row if $row<$t; $b=$row if $row>$b;
            }
        }
        if ($r<0) { print $names qq(        ["$letter"]={advance=$w},\n); next }
        my ($sw,$sh,$dx)=($r-$l+1,$b-$t+1,$l-$start);
        my @ink=map { substr($rows->[$_],4*$l,4*$sw) } $t..$b;
        if ($x+$sw+1>$sheet_width) { $x=0; $y+=$line_height+2; $line_height=0 }
        push @tiles,[$x,$y,\@ink];
        my @solid;
        for my $row (@ink) {
            my $bits=0;
            for my $col (0..$sw-1) {
                $bits|=1<<$col if ord(substr($row,$col*4+3,1))==255;
            }
            push @solid,$bits;
        }
        print $names qq(        ["$letter"]={x=$x,y=$y,w=$sw,h=$sh,dx=$dx,dy=$t,advance=$w,solid={),join(',',@solid),"}},\n";
        $x+=$sw+1; $line_height=$sh if $line_height<$sh;
    }
    print $names "    },kern={\n";
    for my $left (@letters) {
        my @adjust;
        for my $right (@letters) {
            my $pair=encode_utf8($left.$right);
            my $delta=Games::FrozenBubble::CStuff::sdlpango_getsize($font,$pair,-1)->[0]-$advance{$left}-$advance{$right};
            push @adjust,qq(["$right"]=$delta) if $delta;
        }
        print $names qq(        ["$left"]={),join(',',@adjust),"},\n" if @adjust;
    }
    print $names "    }},\n";
}
my $sheet_height=power_of_two($y+$line_height+1);
print $names "    width=$sheet_width,height=$sheet_height,\n}\n";
close $names or die $!;
my $sheet="\0" x ($sheet_width*$sheet_height*4);
for my $tile (@tiles) {
    my ($tx,$ty,$rows)=@$tile;
    for my $i (0..$#$rows) {
        substr($sheet,(($ty+$i)*$sheet_width+$tx)*4,length($rows->[$i]),$rows->[$i]);
    }
}
open my $sheet_file,'>:raw',"$root/Media/name-lettering.tga" or die $!;
print $sheet_file pack('CCCvvCvvvvCC',0,0,2,0,0,0,0,0,$sheet_width,$sheet_height,32,40),$sheet;
close $sheet_file or die $!;
