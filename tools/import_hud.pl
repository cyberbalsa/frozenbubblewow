#!/usr/bin/env perl
# Rasterize the English in-game labels with Frozen Bubble's own SDLPango context.
use strict;
use warnings;
use FindBin;
use SDL;
use SDL::Surface;
use SDL::PixelFormat;
use Games::FrozenBubble::CStuff;

SDL::init(0);
Games::FrozenBubble::CStuff::sdlpango_init();
my $ctx=Games::FrozenBubble::CStuff::sdlpango_createcontext('white','sans 14');
my $root="$FindBin::Bin/../FrozenBubble";
my @labels=('opening clock',0..9, 'Level ', 'Score: ', 'Random level', "'", '"');
my (@sprites,$max_width,$used_height);
$used_height=0; $max_width=0;
for my $label (@labels) {
    my $s=$label eq 'opening clock'
        ? Games::FrozenBubble::CStuff::sdlpango_draw_givenalignment($ctx,qq(2'00"),96,'center')
        : Games::FrozenBubble::CStuff::sdlpango_draw_givenalignment($ctx,"$label",-1,'left');
    my ($w,$h)=($s->w,$s->h);
    my $format=$s->format;
    die 'Expected 8-bit coverage' if ($format->Amask >> $format->Ashift)!=255;
    my $stride=$s->pitch/$format->BytesPerPixel;
    my @coverage;
    for my $y (0..$h-1) {
        push @coverage, [map { ($s->get_pixel($y*$stride+$_) >> $format->Ashift) & 255 } 0..$w-1];
    }
    # Desktop print_ blits a black shadow at (+1,+1), then its white face.
    my @rows;
    for my $y (0..$h) {
        my $row='';
        for my $x (0..$w) {
            my $fg=$y<$h && $x<$w ? $coverage[$y][$x] : 0;
            my $bg=$y && $x ? $coverage[$y-1][$x-1] : 0;
            my $alpha=$fg+$bg*(1-$fg/255);
            my $gray=$alpha ? int(255*$fg/$alpha+0.5) : 255;
            $row.=pack('C4',$gray,$gray,$gray,int($alpha+0.5));
        }
        push @rows,$row;
    }
    push @sprites,[$label,$w,$h,$used_height,\@rows];
    $used_height+=$h+3;
    $max_width=$w+2 if $w+2>$max_width;
}
sub power_of_two { my $n=1; $n*=2 while $n<$_[0]; return $n }
my ($width,$height)=(power_of_two($max_width),power_of_two($used_height));
my $pixels="\0" x ($width*$height*4);
open my $meta,'>',"$root/HUDArt.lua" or die $!;
print $meta "-- Generated by tools/import_hud.pl using the desktop in-game font.\nlocal _,FB=...\n";
print $meta "FB.HUDArt={width=$width,height=$height,labels={\n";
for my $sprite (@sprites) {
    my ($label,$w,$h,$y,$rows)=@$sprite;
    for my $i (0..$#$rows) {
        substr($pixels,($y+$i)*$width*4,length($rows->[$i]),$rows->[$i]);
    }
    $label=~s/"/\\"/g;
    print $meta qq(    ["$label"]={y=$y,w=$w,h=$h},\n);
}
print $meta "}}\n";
print $meta 'FB.MediaInfo["opening-training-clock"]=FB.MediaInfo["training-clock"]', "\n";
close $meta or die $!;
open my $tga,'>:raw',"$root/Media/hud-lettering.tga" or die $!;
print $tga pack('CCCvvCvvvvCC',0,0,2,0,0,0,0,0,$width,$height,32,40),$pixels;
close $tga or die $!;
