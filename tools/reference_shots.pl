#!/usr/bin/env perl
# Generate shot fixtures from the pinned GPLv2 Frozen Bubble checkout.
# The original subroutines operate on SDL sprite top-left coordinates.
use strict;
use warnings;
use POSIX qw(sin cos);
my $root = shift or die "usage: perl tools/reference_shots.pl UPSTREAM\n";
open my $source, '<', "$root/bin/frozen-bubble" or die $!;
my $perl = do { local $/; <$source> };
our ($ROW_SIZE, $BUBBLE_SIZE, %POS, %pdata);
($ROW_SIZE, $BUBBLE_SIZE) = (28, 32);
$POS{p1} = {left_limit=>190, right_limit=>446, top_limit=>44};
$pdata{p1}{oddswap}=0;
sub odd { $_[0]%2 }
sub sqr { $_[0]*$_[0] }
for my $name (qw(calc_real_pos_given_arraypos get_array_yclosest get_array_closest_pos is_collision)) {
    my ($body) = $perl =~ /^(sub \Q$name\E\([^\n]*\n.*?^\})/ms;
    defined $body or die "Missing upstream $name";
    eval $body; die $@ if $@;
}
open my $fh, '<', "$root/share/data/levels" or die $!;
local $/="";
my @levels=<$fh>;
print "-- Generated by tools/reference_shots.pl with the pinned upstream collision and grid routines.\nreturn {\n";
for my $number (1, 2, 3, 11, 25, 67, 100) {
    my @grid;
    my $row=0;
    for my $line (split /\n/,$levels[$number-1]) {
        next unless $line =~ /\S/;
        my @cells=split ' ',$line;
        for my $col (0..$#cells) {
            push @grid,[calc_real_pos_given_arraypos($col,$row,'p1')] unless $cells[$col] eq '-';
        }
        $row++;
    }
    for my $angle (-1.4,-1.1,-0.7,-0.3,0,0.3,0.7,1.1,1.4) {
        my ($x,$y)=(302,390);
        my ($vx,$vy)=(10*sin($angle),-10*cos($angle));
        for my $tick (1..400) {
            my ($oldx,$oldy)=($x,$y);
            $x+=$vx; $y+=$vy;
            if ($x<190) { $x=380-$x; $vx=-$vx }
            if ($x>414) { $x=828-$x; $vx=-$vx }
            my @cell;
            if ($y<=44) { @cell=get_array_closest_pos($x,$y,'p1') }
            elsif (grep { is_collision({x=>$x,y=>$y},@$_) } @grid) {
                @cell=get_array_closest_pos(($x+$oldx)/2,($y+$oldy)/2,'p1');
            }
            if (@cell) {
                my $key=$cell[1]*8+$cell[0]+1;
                print "    {$number,$angle,$tick,$key},\n";
                last;
            }
        }
    }
}
print "}\n";
