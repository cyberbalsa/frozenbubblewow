#!/usr/bin/env perl
# Generate the campaign regression fixture with the upstream SDL engine.
use strict;
use warnings;
use File::Spec;
use File::Temp qw(tempfile);

my ($root, $level) = @ARGV;
die "usage: perl $0 UPSTREAM [LEVEL]\n" unless $root;
$root = File::Spec->rel2abs($root);
if (!defined $level) {
    print "-- Generated by tools/demos/reference_campaign.pl using desktop Frozen Bubble.\nreturn {\n";
    for my $board (1 .. 100) {
        system($^X, $0, $root, $board) == 0 or die "Failed on level $board";
    }
    print "}\n";
    exit;
}
die "Expected a campaign level" unless $level =~ /^\d+$/ && $level >= 1 && $level <= 100;
my $ticks = $level == 17 ? 160 : $level == 1 ? 1600 : 845;
my $seed = $level == 17 ? 4 : $level * 7;
my ($keys, $file) = tempfile(UNLINK => 1);
print $keys "record_protocol:0\nplayers:p1\ngametype:\ncurrent_level:$level\nchainreaction:0\nsrand:$seed\n";
sub action { print $keys "frame_action:$_[0]|p1|$_[1]|$_[2]\n" }
if ($level == 17) {
    # One bank shot breaks the top pair and drops the seven bubbles below it.
    action(1, 'left', 1); action(19, 'left', 0); action(19, 'fire', 1);
} else {
    my @turns = (7, 41, 10, 30, 17, 40, 32, 19);
    for (my $shot = 1; 1 + ($shot - 1) * 55 < $ticks; $shot++) {
        my $start = 1 + ($shot - 1) * 55;
        my $direction = $shot % 2 ? 'right' : 'left';
        my $fire = $start + 1 + $turns[$shot % @turns];
        action($start, 'center', 1); action($start + 1, 'center', 0);
        action($start + 1, $direction, 1);
        action($fire, $direction, 0); action($fire, 'fire', 1);
    }
}
action(3000, 'left', 0);
close $keys;
open my $source, '<', "$root/bin/frozen-bubble" or die $!;
my $src = do { local $/; <$source> };
close $source;
my ($step, $checksum, @sounds);
open my $output, '>&', \*STDOUT or die $!;
open STDOUT, '>', File::Spec->devnull or die $!;

sub hook {
    my ($from, $to) = @_;
    my $count = $src =~ s/\Q$from\E/$to/g;
    die "Expected one upstream hook for $from" unless $count == 1;
}
hook('$FPATH = $Games::FrozenBubble::Config::FPATH;', '$FPATH = $root . "/share";');
hook('    replay($replayparam);', '    replay($replayparam); die "Recording ended before $ticks frames";');
hook('sub play_sound($) {', 'sub play_sound($) { push @sounds, $_[0] if $playdata;');
hook('    handle_graphics(\&put_image);' . "\n" . '    $frame++;', q!
    handle_graphics(\&put_image);
    ++$step;
    my @cells = (0) x 112;  # A piston can push the fatal shot into row fourteen.
    for my $b (@{$sticked_bubbles{p1}}) {
        $cells[$b->{cy}*8 + $b->{cx}] = 1 + get_bubble_num($b);
    }
    my $sprite = sub { join(',', 1 + get_bubble_num($_[0]), int($_[0]{x}), int($_[0]{y})) };
    my $flying = $launched_bubble{p1} ? $sprite->($launched_bubble{p1}) : '-';
    my $falling = join(';', sort map { $sprite->($_) } @{$falling_bubble{p1}});
    my $state = $pdata{state} =~ /^won/ ? 'won' : $pdata{state} =~ /^lost/ ? 'lost' : 'playing';
    my $loaded = $state eq 'lost' ? 0 : 1 + get_bubble_num($tobe_launched{p1});
    my $next = $state eq 'lost' ? 0 : 1 + get_bubble_num($next_bubble{p1});
    my $row = join('|', $step, $state, join('', @cells), $pdata{p1}{newrootlevel}, $pdata{p1}{newroot},
                   $flying, $falling, $loaded, $next, join(',', @sounds)) . "\n";
    $checksum = ($checksum*131 + $_) % 2147483647 for unpack('C*', $row);
    @sounds = ();
    if ($step == $ticks) {
        print $output "    [$level]=$checksum,\n";
        exit 0;
    }
    $frame++;
!);
hook('$to_wait > 0 and Games::FrozenBubble::CStuff::fbdelay($to_wait);' . "\n" . '    $saveframes and save_frame();', '');
$checksum = 0;
@ARGV = ('--no-sound', '--replay', $file);
$ENV{SDL_VIDEODRIVER} = $ENV{SDL_AUDIODRIVER} = 'dummy';
{ no warnings; eval $src; }
die $@ if $@;
