#!/usr/bin/env python3
"""Prepare GPU textures and collision masks from the desktop title artwork."""
import argparse
import math
import random
import struct
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1] / "FrozenBubble"


def palette_blp(path, image):
    indexed = image.quantize(colors=256, dither=Image.Dither.NONE)
    palette = indexed.getpalette()
    bgra = bytearray(1024)
    for i in range(0, len(palette), 3):
        bgra[i//3*4:i//3*4+3] = bytes(reversed(palette[i:i+3]))
    data = indexed.tobytes()
    header = struct.pack("<4sI4B2I", b"BLP2", 1, 1, 0, 0, 0, *image.size)
    header += struct.pack("<16I", 1172, *([0]*15)) + struct.pack("<16I", len(data), *([0]*15))
    path.write_bytes(header + bgra + data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("upstream", type=Path)
    gfx = parser.parse_args().upstream / "share/gfx/menu"
    logo = Image.open(gfx / "fblogo.png").convert("RGBA")
    mask = Image.open(gfx / "fblogo-mask.png").convert("RGB")
    w, h = logo.size
    out = ROOT / "Media/Title"
    out.mkdir(exist_ok=True)
    # Transparent padding permits UVs to extend beyond the original canvas.
    padded = Image.new("RGBA", (256, 256))
    padded.paste(logo, (24, 24))
    padded.save(out / "logo.tga")

    flake = Image.new("RGBA", (8, 8))
    for y in range(1, 4):
        for x in range(1, 4):
            flake.putpixel((x, y), (255, 255, 255, 128 if x != 2 and y != 2 else 255))
    flake.save(out / "flake.tga")

    # Broken-TV bursts in CStuff.xs assign random per-pixel throughness.
    noise = Image.new("RGBA", (1024, 512))
    rng = random.Random(2002)
    for i in range(20):
        frame = logo.copy()
        frame.putalpha(Image.frombytes("L", logo.size, bytes(
            int(a * (0.2 + rng.randint(1, 100)/100)) % 256 for a in logo.getchannel("A").tobytes()
        )))
        noise.paste(frame, (i % 5 * 192 + 1, i // 5 * 121 + 1))
    noise.save(out / "noise.tga")

    # Only the additive light contribution moves. The logo underneath supplies
    # its original alpha. Distances beyond 32 pixels have zero gain upstream.
    centers = {}
    frames = []
    patch = 64
    for tick in range(round(1000*math.pi)):
        x = int(w/(2.5 + 0.3*math.sin(tick/500))*math.sin(tick/100) + w//2)
        y = int(h/(2.5 + 0.3*math.cos(tick/500))*math.cos(tick/100) + h//2 + 10)
        centers.setdefault((x, y), len(centers))
        frames.append(centers[x, y])
    cells = 256
    sheet = None
    pixels = logo.load()
    for (cx, cy), index in centers.items():
        if index % cells == 0:
            sheet = Image.new("RGB", (1024, 1024))
            dest = sheet.load()
        ox, oy = index % 16 * patch, index % cells // 16 * patch
        for y in range(max(0, cy-32), min(h, cy+32)):
            for x in range(max(0, cx-32), min(w, cx+32)):
                d = (x-cx)**2 + (y-cy)**2 - 3 - 4*(y == cy) - 2*(x == cx)
                gain = 50 if d <= 0 else 1 + 20/d
                if gain > 1.02:
                    *rgb, alpha = pixels[x, y]
                    dest[ox+x-cx+32, oy+y-cy+32] = tuple(
                        round((min(255, int(c*gain))-c)*alpha/255) for c in rgb)
        if index % cells == cells-1 or index == len(centers)-1:
            palette_blp(out / f"glint-{index//cells+1}.blp", sheet)
    rows = ["-- Generated by tools/import_title_logo.py from Frozen Bubble's title artwork.",
            "local _, FB = ...", "FB.LogoData={", "white={"]
    for y in range(h):
        rows.append('"' + "".join("1" if mask.getpixel((x,y)) == (255,255,255) else "0" for x in range(w)) + '",')
    rows.append("}, alpha={")
    for y in range(h):
        rows.append('"' + logo.getchannel("A").crop((0,y,w,y+1)).tobytes().hex() + '",')
    rows.append("}, centers={")
    for x, y in centers:
        rows.append(f"{x+256*y},")
    rows.append("}, frames={")
    for i in range(0, len(frames), 32):
        rows.append(",".join(map(str,frames[i:i+32]))+",")
    rows.append("}}")
    (ROOT / "LogoData.lua").write_text("\n".join(rows)+"\n")


if __name__ == "__main__":
    main()
